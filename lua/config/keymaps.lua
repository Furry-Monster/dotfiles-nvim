local map = vim.keymap.set
map('n', '<Esc>', '<cmd>nohlsearch<cr>')
map('n', '<leader>w', '<cmd>write<cr>', { desc = 'Save' })
require('config.navigation').setup()
map('n', '<leader>q', '<cmd>copen<cr>', { desc = 'Quickfix' })
map('n', ']q', '<cmd>cnext<cr>', { desc = 'Next build error' })
map('n', '[q', '<cmd>cprevious<cr>', { desc = 'Previous build error' })
map('n', '<leader>xx', vim.diagnostic.setqflist, { desc = 'Diagnostics to quickfix' })
map('n', '<leader>xd', vim.diagnostic.open_float, { desc = 'Line diagnostics' })
map('n', '<leader>tt', function()
    require('core.terminal').terminal()
end, { desc = 'Project terminal' })
map('n', '<leader>ts', function()
    require('core.terminal').run()
end, { desc = 'Run current Bash/PowerShell script' })
map('t', '<Esc><Esc>', '<C-\\><C-n>', { desc = 'Terminal normal mode' })
vim.api.nvim_create_user_command('WorkflowHealth', function()
    vim.cmd('checkhealth core vim.lsp')
end, {})
