local function map(mode, lhs, rhs, desc)
    vim.keymap.set(mode, lhs, rhs, { desc = desc, silent = true })
end
map("n", "<Esc>", "<cmd>nohlsearch<cr>", "清除搜索高亮")
map({ "n", "i", "x" }, "<C-s>", "<Esc><cmd>write<cr>", "保存文件")
map("n", "<leader>w", "<cmd>write<cr>", "保存")
map("n", "<leader>q", "<cmd>confirm quit<cr>", "关闭窗口")
for _, key in ipairs({ "h", "j", "k", "l" }) do
    map("n", "<C-" .. key .. ">", "<C-w>" .. key, "切换窗口")
end
map("t", "<C-\\><C-\\>", "<C-\\><C-n>", "退出终端输入模式")
map("n", "<S-h>", "<cmd>bprevious<cr>", "上一个 buffer")
map("n", "<S-l>", "<cmd>bnext<cr>", "下一个 buffer")
map("n", "<leader>bd", "<cmd>confirm bdelete<cr>", "关闭 buffer")
map("n", "]q", "<cmd>cnext<cr>", "下一个 quickfix")
map("n", "[q", "<cmd>cprevious<cr>", "上一个 quickfix")
map("n", "<leader>xq", "<cmd>copen<cr>", "Quickfix")
map("n", "<leader>xx", vim.diagnostic.setqflist, "工程诊断列表")
map("n", "<leader>xl", vim.diagnostic.setloclist, "当前文件诊断列表")
map("n", "<leader>e", vim.diagnostic.open_float, "当前位置诊断")
map("n", "<leader>ud", function()
    vim.diagnostic.enable(not vim.diagnostic.is_enabled())
end, "切换诊断")
map("n", "<leader>uv", function()
    local current = vim.diagnostic.config().virtual_text
    vim.diagnostic.config({ virtual_text = not current })
end, "切换行内诊断")
map("n", "<leader>uh", function()
    vim.lsp.inlay_hint.enable(not vim.lsp.inlay_hint.is_enabled({ bufnr = 0 }), { bufnr = 0 })
end, "切换类型/参数提示")
map("n", "<leader>ug", "<cmd>GitToggle<cr>", "Git 总开关")
map("n", "<leader>ua", function()
    require("config.ai").toggle()
end, "AI 总开关")
map("n", "<leader>uQ", "<cmd>IntegrationsOff<cr>", "一键关闭全部 AI/Git")
map("n", "<leader>ut", function()
    require("config.terminal").open(vim.o.shell, "terminal")
end, "工程终端")
map("n", "<leader>ph", "<cmd>checkhealth workbench<cr>", "配置健康检查")
map("n", "<leader>pt", "<cmd>ProjectTrust<cr>", "加载可信项目设置")
map("n", "<leader>pr", "<cmd>ProjectRoot<cr>", "查看工程根目录")
